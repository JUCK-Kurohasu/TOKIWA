type ProposalState = { proposal?: { title: string; content: string; rationale?: string } } | null;
const KNOWN_META = new Set(["rationale", "advisory_id", "vuln_ids", "llm_call_id"]);

function str(v: unknown): string | null {
  return typeof v === "string" && v ? v : null;
}

export function ProposalsTab() {
  const L = useLocal(strings);
  const can = useCan();
  const qc = useQueryClient();
  const location = useLocation();
  const navProposal = (location.state as ProposalState)?.proposal;
  const [params, update] = useUrlParams();
  const q = params.get("q") ?? "";
  const selected = params.get("rule");
  const [confirm, setConfirm] = useState<"approve" | "reject" | null>(null);
  const [editing, setEditing] = useState<Rule | null>(null);
  const [draftOpen, setDraftOpen] = useState(false);
  const [validation, setValidation] = useState<{ id: string; result: RuleValidation } | null>(null);

  const list = useQuery({
    queryKey: ["rules", "list", { status: "proposed" }],
    queryFn: () => api.get<Page<Rule>>("/rules", { status: "proposed", limit: 200 }),
  });
  const items = list.data?.items ?? [];
  const needle = q.trim().toLowerCase();
  const qMatch = needle
    ? (items.find((r) => r.title.toLowerCase() === needle) ??
      items.find((r) => r.title.toLowerCase().includes(needle)))
    : undefined;

  // Arriving from an advisory ("Review as rule"): preselect the matching proposal.
  useEffect(() => {
    if (!selected && qMatch) update({ rule: qMatch.id });
  }, [selected, qMatch, update]);

  const current = items.find((r) => r.id === selected) ?? null;

  const validate = useMutation({
    mutationFn: (r: Rule) => api.post<RuleValidation>("/rules/validate", { content: r.content }),
    onSuccess: (result, r) => setValidation({ id: r.id, result }),
  });

  const decide = useMutation({
    mutationFn: ({ r, action }: { r: Rule; action: "approve" | "reject" }) =>
      action === "approve"
        ? api.post<Rule>(`/rules/${encodeURIComponent(r.id)}/approve`)
        : api.patch<Rule>(`/rules/${encodeURIComponent(r.id)}`, { status: "rejected" }),
    onSuccess: () => {
      setConfirm(null);
      update({ rule: null, q: null });
      qc.invalidateQueries({ queryKey: ["rules"] });
    },
  });

  const otherMeta = current
    ? Object.fromEntries(Object.entries(current.meta ?? {}).filter(([k]) => !KNOWN_META.has(k)))
    : {};
  const vulnIds = Array.isArray(current?.meta?.vuln_ids)
    ? (current.meta.vuln_ids as unknown[]).filter((x): x is string => typeof x === "string")
    : [];

  return (
    <div className="space-y-3">
      {needle && !list.isLoading && !qMatch && (
        <Card className="border-ai/30">
          <div className="flex flex-wrap items-center justify-between gap-3 px-4 py-3">
            <p className="text-sm text-muted">{L.notQueued.replace("{q}", q)}</p>
            {navProposal && can.analyst && (
              <Button
                variant="outline"
                className="border-ai/40 text-ai hover:bg-ai/10"
                onClick={() => setDraftOpen(true)}
              >
                <Pencil className="h-4 w-4" aria-hidden />
                {L.openDraft}
              </Button>
            )}
          </div>
        </Card>
      )}

      <div className="grid gap-4 lg:grid-cols-[minmax(0,2fr)_minmax(0,3fr)]">
        <Card className="h-fit">
          <QueryView
            query={list}
            className="p-4"
            rows={5}
            isEmpty={(d) => d.items.length === 0}
            empty={<EmptyState title={L.empty} hint={L.emptyHint} icon={<Inbox className="h-6 w-6" />} />}
          >
            {(page) => (
              <ul className="divide-y divide-line">
                {page.items.map((r) => (
                  <li key={r.id}>
                    <button
                      type="button"
                      aria-current={r.id === selected ? "true" : undefined}
                      onClick={() => update({ rule: r.id })}
                      className={cn(
                        "flex w-full flex-col gap-1 px-3 py-2.5 text-left transition-colors hover:bg-surface-2",
                        r.id === selected && "bg-ai/10 shadow-[inset_3px_0_0_0_var(--color-ai)]",
                      )}
                    >
                      <span className="truncate text-sm font-medium">{r.title}</span>
                      <span className="flex items-center gap-2 text-[11px] text-muted">
                        <RuleSourceBadge source={r.source} />
                        <span className="ml-auto">{timeAgo(r.created_at)}</span>
                      </span>
                    </button>
                  </li>
                ))}
              </ul>
            )}
          </QueryView>
        </Card>

        <Card className="min-w-0">
          {!current ? (
            <EmptyState title={L.select} />
          ) : (
            <div className="space-y-4 p-4">
              <div className="space-y-1.5">
                <div className="flex flex-wrap items-center gap-2">
                  <RuleSourceBadge source={current.source} />
                  {current.source === "llm" && <AiGeneratedBadge />}
                  <span className="text-xs text-muted">
                    {L.created}: {formatDateTime(current.created_at)}
                  </span>
                </div>
                <h3 className="text-base font-semibold">{current.title}</h3>
              </div>

              <p className="rounded-md border border-sev-medium/30 bg-sev-medium/10 px-3 py-2 text-xs text-sev-medium">
                {L.caution}
              </p>

              <section>
                <h4 className="mb-1 text-xs font-semibold uppercase tracking-wide text-muted">
                  {L.rationale}
                </h4>
                <p className="whitespace-pre-wrap text-sm">{str(current.meta?.rationale) ?? L.noRationale}</p>
              </section>

              {(str(current.meta?.advisory_id) || vulnIds.length > 0 || str(current.meta?.llm_call_id)) && (
                <div className="flex flex-wrap gap-x-4 gap-y-1 text-xs">
                  {str(current.meta?.advisory_id) && (
                    <Link
                      className="text-accent hover:underline"
                      to={`/intel?tab=advisories&adv=${encodeURIComponent(String(current.meta.advisory_id))}`}
                    >
                      {L.advisory}
                    </Link>
                  )}
                  {vulnIds.length > 0 && (
                    <span className="flex flex-wrap items-center gap-1 text-muted">
                      {L.vulns}:
                      {vulnIds.map((id) => (
                        <Link
                          key={id}
                          to={`/intel?vuln=${encodeURIComponent(id)}`}
                          className="font-mono text-accent hover:underline"
                        >
                          {id}
                        </Link>
                      ))}
                    </span>
                  )}
                  {str(current.meta?.llm_call_id) && (
                    <Link
                      className="text-ai hover:underline"
                      to={`/llm?tab=calls&call=${encodeURIComponent(String(current.meta.llm_call_id))}`}
                    >
                      {L.llmCall}
                    </Link>
                  )}
                </div>
              )}

              <section>
                <h4 className="mb-1 text-xs font-semibold uppercase tracking-wide text-muted">{L.content}</h4>
                <SigmaEditor label={L.content} value={current.content} readOnly rows={16} />
              </section>

              {validation?.id === current.id && <ValidationResult result={validation.result} />}
              {validate.error ? <ApiErrorState error={validate.error} /> : null}

              {Object.keys(otherMeta).length > 0 && (
                <details className="text-xs">
                  <summary className="cursor-pointer text-muted hover:text-fg">{L.otherMeta}</summary>
                  <JsonView value={otherMeta} className="mt-2" />
                </details>
              )}

              {can.analyst ? (
                <div className="flex flex-wrap justify-end gap-2 border-t border-line pt-3">
                  <Button
                    variant="outline"
                    onClick={() => validate.mutate(current)}
                    disabled={validate.isPending}
                  >
                    {validate.isPending ? (
                      <Spinner className="h-3.5 w-3.5" />
                    ) : (
                      <ShieldCheck className="h-4 w-4" aria-hidden />
                    )}
                    {L.validate}
                  </Button>
                  <Button variant="outline" onClick={() => setEditing(current)}>
                    <Pencil className="h-4 w-4" aria-hidden />
                    {L.edit}
                  </Button>
                  <Button
                    variant="outline"
                    className="hover:border-sev-critical/50 hover:text-sev-critical"
                    onClick={() => {
                      decide.reset();
                      setConfirm("reject");
                    }}
                  >
                    <X className="h-4 w-4" aria-hidden />
                    {L.reject}
                  </Button>
                  <Button
                    onClick={() => {
                      decide.reset();
                      setConfirm("approve");
                    }}
                  >
                    <Check className="h-4 w-4" aria-hidden />
                    {L.approve}
                  </Button>
                </div>
              ) : (
                <p className="border-t border-line pt-3 text-xs text-muted">{L.readOnly}</p>
              )}
            </div>
          )}
        </Card>
      </div>

      {current && (
        <ConfirmDialog
          open={confirm !== null}
          tone={confirm === "approve" ? "primary" : "danger"}
          title={confirm === "approve" ? L.approveTitle : L.rejectTitle}
          body={(confirm === "approve" ? L.approveBody : L.rejectBody).replace("{name}", current.title)}
          confirmLabel={confirm === "approve" ? L.approve : L.reject}
          busy={decide.isPending}
          error={decide.error}
          onConfirm={() => confirm && decide.mutate({ r: current, action: confirm })}
          onClose={() => setConfirm(null)}
        />
      )}
      {editing && <RuleEditorDialog key={editing.id} rule={editing} onClose={() => setEditing(null)} />}
      {draftOpen && navProposal && (
        <RuleEditorDialog
          key="draft"
          rule={null}
          draft={{ content: navProposal.content, fromLlm: true }}
          onClose={() => setDraftOpen(false)}
        />
      )}
    </div>
  );
}
