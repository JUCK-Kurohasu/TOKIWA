def _is_urgent(vuln: VulnRecord, epss_threshold: float) -> bool:
    return vuln.kev or (vuln.epss or 0.0) >= epss_threshold


async def advise_for_vulns(vuln_ids: Iterable[str]) -> list[Advisory]:
    """Immediate advisories for KEV / high-EPSS vulns that have open matches (P1/P2)."""
    threshold = get_settings().intel.epss_alert_threshold
    out: list[Advisory] = []
    for vid in dict.fromkeys(vuln_ids):
        try:
            vuln = await _load_vuln(vid)
            if vuln is None or not _is_urgent(vuln, threshold):
                continue
            if not await _matched_assets(vid):
                continue
            adv, created = await generate_advisory(vid)
            if created:
                out.append(adv)
        except Exception:
            log.exception("advisory generation failed for %s", vid)
    return out


async def _on_vuln_matched(payload: Any) -> None:
    vuln_id = getattr(payload, "vuln_id", None) or (
        payload.get("vuln_id") if isinstance(payload, dict) else None
    )
    if isinstance(vuln_id, str) and vuln_id:
        await advise_for_vulns([vuln_id])


async def advise_pending(limit: int = MAX_PENDING_PER_RUN) -> list[Advisory]:
    """Periodic catch-up: vulns with open matches but no current advisory, most urgent first (capped)."""
    threshold = get_settings().intel.epss_alert_threshold
    async with session_scope() as session:
        vids = list(
            (
                await session.execute(
                    select(VulnMatchRow.vuln_id)
                    .where(VulnMatchRow.status == MatchStatus.OPEN.value)
                    .distinct()
                )
            ).scalars()
        )
        rows = (
            (await session.execute(select(VulnRow).where(VulnRow.id.in_(vids)))).scalars().all()
            if vids
            else []
        )
        vulns = [VulnRecord.model_validate(r) for r in rows]
    vulns.sort(
        key=lambda v: (
            PRIORITY_RANK[rule_priority(v, True, threshold)[0]],
            -(v.epss or 0.0),
            -(v.cvss_score or 0.0),
            v.id,
        )
    )
    out: list[Advisory] = []
    for v in vulns:
        if len(out) >= limit:
            break
        try:
            adv, created = await generate_advisory(v.id)
        except Exception:
            log.exception("advisory generation failed for %s", v.id)
            continue
        if created:
            out.append(adv)
    return out


@on_startup
async def _subscribe_advisor() -> None:
    bus.subscribe("intel.vuln_matched", _on_vuln_matched)


@periodic(
    "intel.advise",
    every_seconds=lambda s: max(15, s.intel.sync_interval_minutes) * 60,
    initial_delay=300,
    enabled=lambda s: s.intel.enabled,
)
async def advise_pending_job() -> None:
    await advise_pending()
