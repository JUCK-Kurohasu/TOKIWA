async def generate_advisory(vuln_id: str, *, force: bool = False) -> tuple[Advisory, bool]:
    """Generate (or reuse) the advisory for ``vuln_id``. Returns (advisory, created).

    Raises ``LookupError`` when the vulnerability is unknown.
    """
    settings = get_settings()
    vuln = await _load_vuln(vuln_id)
    if vuln is None:
        raise LookupError(f"unknown vulnerability {vuln_id}")
    async with _locks.get(f"advisory:{vuln_id}"):
        assets = await _matched_assets(vuln_id)
        asset_ids = sorted(a.id for a in assets)
        floor, reasons = rule_priority(vuln, bool(assets), settings.intel.epss_alert_threshold)
        if not force:
            existing = await find_recent_advisory(vuln_id, asset_ids, floor)
            if existing is not None:
                return existing, False

        lang = settings.llm.output_language
        template = template_analysis(vuln, assets, floor, reasons, lang)
        gw = get_gateway()
        req = StructuredRequest(
            purpose=LLMPurpose.ADVISORY,
            tier=LLMTier.DEEP,
            system=advisory_system(lang),
            user=build_advisory_user(
                vuln=_vuln_prompt_dict(vuln),
                assets=[a.prompt_dict() for a in assets],
                context={
                    "rule_priority": floor.value,
                    "priority_reasons": reasons,
                    "epss_alert_threshold": settings.intel.epss_alert_threshold,
                    "asset_ids": asset_ids,
                },
            ),
            prompt_version=ADVISORY_PROMPT.ref,
            related={"vuln_id": vuln.id},
        )
        token = _TEMPLATE.set(template)
        try:
            async with _llm_slots.get():
                result = await gw.structured(req, AdvisoryAnalysis)
        finally:
            _TEMPLATE.reset(token)

        meta: dict[str, Any] = {
            "kind": "vuln",
            "input_asset_ids": asset_ids,
            "rule_priority": floor.value,
            "priority_reasons": reasons,
            "llm_status": str(result.status),
            "provider": result.provider,
        }
        valid_rules: list[tuple[ProposedRule, str | None, str]] = []
        if result.ok and result.output is not None:
            out = result.output
            allowed = set(asset_ids)
            kept = [a for a in dict.fromkeys(out.affected_assets) if a in allowed]
            rejected_assets = [a for a in dict.fromkeys(out.affected_assets) if a not in allowed]
            rejected_rules: list[dict[str, Any]] = []
            accepted_rules: list[ProposedRule] = []
            for pr in out.proposed_rules[:3]:
                ok, errors, title, validator = validate_proposed_rule(pr)
                if ok:
                    accepted_rules.append(pr)
                    valid_rules.append((pr, title, validator))
                else:
                    rejected_rules.append(
                        {"title": pr.title[:200], "errors": errors[:10], "validator": validator}
                    )
            final_priority = more_urgent(floor, out.priority)
            analysis = out.model_copy(
                update={
                    "priority": final_priority,
                    "affected_assets": kept,
                    "proposed_rules": accepted_rules,
                    "references": filter_references(
                        out.references, vuln.references, TRUSTED_REFERENCE_DOMAINS
                    ),
                }
            )
            meta.update(
                source="mock" if result.provider == "mock" else "llm",
                llm_priority=out.priority.value,
                rejected_asset_ids=rejected_assets,
                rejected_rules=rejected_rules,
            )
        else:
            analysis = template
            meta.update(source="template", llm_error=(result.error or "")[:500])

        advisory = await _store_advisory(
            vuln_ids=[vuln.id], analysis=analysis, meta=meta, llm_call_id=result.call_id, rules=valid_rules
        )
    return advisory, True


async def _store_advisory(
    *,
    vuln_ids: list[str],
    analysis: AdvisoryAnalysis,
    meta: dict[str, Any],
    llm_call_id: str | None,
    rules: list[tuple[ProposedRule, str | None, str]] | None = None,
) -> Advisory:
    advisory_id = new_id()
    rule_ids: list[str] = []
    async with session_scope() as session:
        for pr, title, validator in rules or []:
            dup = (
                await session.execute(select(RuleRow.id).where(RuleRow.content == pr.content).limit(1))
            ).scalar_one_or_none()
            if dup is not None:
                rule_ids.append(dup)
                continue
            rule = RuleRow(
                id=new_id(),
                kind="sigma",
                title=(title or pr.title or "LLM proposed rule")[:512],
                content=pr.content,
                status=RuleStatus.PROPOSED.value,
                source=RuleSource.LLM.value,
                meta={
                    "advisory_id": advisory_id,
                    "vuln_ids": vuln_ids,
                    "rationale": pr.rationale[:4000],
                    "validated_by": validator,
                    "proposed_title": pr.title[:512],
                },
            )
            session.add(rule)
            rule_ids.append(rule.id)
            await record_audit(
                SYSTEM_ACTOR,
                "rule.proposed",
                target=rule.id,
                details={"advisory_id": advisory_id, "vuln_ids": vuln_ids, "validated_by": validator},
                session=session,
            )
        meta = {**meta, "rule_ids": rule_ids}
        row = AdvisoryRow(
            id=advisory_id,
            created_at=utcnow(),
            vuln_ids=vuln_ids,
            title=analysis.title[:512],
            priority=analysis.priority.value,
            status="new",
            analysis={**analysis.model_dump(mode="json"), "_meta": meta},
            llm_call_id=llm_call_id,
        )
        session.add(row)
        await session.flush()
        advisory = Advisory.model_validate(row)
    await bus.publish("intel.advisory", advisory)
    return advisory


async def create_research_advisory(
    *,
    title: str,
    summary: str,
    exploitation: str,
    relevance: str,
    actions: list[str],
    references: list[str],
    cve_ids: list[str],
    asset_ids: list[str],
    report_id: str,
) -> Advisory | None:
    """Advisory candidate from a highly relevant research finding (no extra LLM call). Deduplicated by title."""
    finding_key = short_hash(re.sub(r"\s+", " ", title.strip().lower()))
    since = utcnow() - timedelta(days=DEDUP_DAYS)
    async with session_scope() as session:
        rows = (
            await session.execute(
                select(AdvisoryRow.analysis).where(
                    AdvisoryRow.created_at >= since,
                    cast(AdvisoryRow.analysis, String).contains(finding_key, autoescape=True),
                )
            )
        ).scalars()
        for analysis in rows:
            meta = (analysis or {}).get("_meta") or {}
            if meta.get("kind") == "research" and meta.get("finding_key") == finding_key:
                return None
    in_the_wild = "wild" in exploitation.lower() or "exploited" in exploitation.lower()
    priority = Priority.P2 if in_the_wild else Priority.P3
    analysis = AdvisoryAnalysis(
        title=f"[Research] {title}"[:500],
        priority=priority,
        summary=summary,
        exploitation_status=exploitation,
        affected_assets=asset_ids,
        impact=relevance,
        mitigations=actions[:10],
        detection_opportunities=[],
        proposed_rules=[],
        references=references[:10],
        confidence=0.4,
    )
    meta = {
        "kind": "research",
        "finding_key": finding_key,
        "report_id": report_id,
        "input_asset_ids": sorted(asset_ids),
        "source": "research",
    }
    return await _store_advisory(vuln_ids=cve_ids, analysis=analysis, meta=meta, llm_call_id=None)


