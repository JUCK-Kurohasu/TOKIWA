def _is_http_url(u: object) -> bool:
    if not isinstance(u, str) or len(u) > 2048:
        return False
    try:
        parts = urlsplit(u.strip())
    except ValueError:
        return False
    return parts.scheme in ("http", "https") and bool(parts.hostname)


def domain_allowed(url: str, domains: Iterable[str]) -> bool:
    try:
        host = (urlsplit(url.strip()).hostname or "").lower().rstrip(".")
    except ValueError:
        return False
    if not host:
        return False
    return any(host == d or host.endswith("." + d) for d in (x.lower().strip(".") for x in domains) if d)


def filter_references(
    refs: Iterable[str], known: Iterable[str], domains: Iterable[str], limit: int = 20
) -> list[str]:
    known_set = {k.strip() for k in known if isinstance(k, str)}
    domain_list = list(domains)
    out: list[str] = []
    for r in refs:
        if not _is_http_url(r):
            continue
        r = r.strip()
        if (r in known_set or domain_allowed(r, domain_list)) and r not in out:
            out.append(r)
        if len(out) >= limit:
            break
    return out


Validator = Callable[[str], tuple[bool, list[str], str | None]]


def _load_sigma_validator() -> Validator | None:
    """``tokiwa.detect.sigma.validate_rule(content) -> (valid, errors, title)`` (sigma module), imported lazily."""
    for mod_name in ("tokiwa.detect.sigma", "tokiwa.detect.sigma.parser"):
        try:
            mod = importlib.import_module(mod_name)
        except Exception:  # noqa: S112 - the sigma module may not exist yet (parallel development)
            continue
        fn = getattr(mod, "validate_rule", None)
        if callable(fn):
            return fn
    return None


_CONDITION_KEYWORDS = frozenset({"and", "or", "not", "of", "them", "all", "any", "near", "by"})


def yaml_structure_check(content: str) -> tuple[bool, list[str], str | None]:
    """Fallback validation when the Sigma validator is unavailable: YAML syntax + minimal Sigma structure."""
    errors: list[str] = []
    if len(content) > MAX_RULE_CHARS:
        return False, [f"rule too large ({len(content)} > {MAX_RULE_CHARS} chars)"], None
    try:
        doc = yaml.safe_load(content)
    except yaml.YAMLError as exc:
        return False, [f"invalid YAML: {exc}"[:500]], None
    if not isinstance(doc, dict):
        return False, ["rule must be a YAML mapping"], None
    title = doc.get("title")
    if not isinstance(title, str) or not title.strip():
        errors.append("missing 'title'")
        title = None
    if not isinstance(doc.get("logsource"), dict):
        errors.append("missing 'logsource' mapping")
    detection = doc.get("detection")
    if not isinstance(detection, dict):
        errors.append("missing 'detection' mapping")
    else:
        condition = detection.get("condition")
        conditions = [condition] if isinstance(condition, str) else condition
        selections = {k for k, v in detection.items() if k != "condition" and isinstance(v, dict | list)}
        if not conditions or not all(isinstance(c, str) and c.strip() for c in conditions):
            errors.append("missing 'detection.condition'")
        elif not selections:
            errors.append("detection has no selection")
        else:
            for cond in conditions:
                for ident in re.findall(r"[A-Za-z_][A-Za-z0-9_*]*", cond):
                    if ident.lower() in _CONDITION_KEYWORDS:
                        continue
                    if "*" in ident:
                        pattern = re.compile("^" + re.escape(ident).replace(r"\*", ".*") + "$")
                        if not any(pattern.match(s) for s in selections):
                            errors.append(f"condition references unknown selection pattern '{ident}'")
                    elif ident not in selections:
                        errors.append(f"condition references unknown selection '{ident}'")
    level = doc.get("level")
    if level is not None and str(level).lower() not in _VALID_LEVELS:
        errors.append(f"invalid level '{level}'")
    return not errors, errors, title


def validate_proposed_rule(rule: ProposedRule) -> tuple[bool, list[str], str | None, str]:
    """(valid, errors, title, validator) where validator is "sigma" or "yaml"."""
    if rule.kind.strip().lower() != "sigma":
        return False, [f"unsupported rule kind '{rule.kind}'"], None, "kind"
    content = rule.content or ""
    if not content.strip():
        return False, ["empty rule"], None, "kind"
    if len(content) > MAX_RULE_CHARS:
        return False, [f"rule too large ({len(content)} chars)"], None, "kind"
    validator = _load_sigma_validator()
    if validator is None:
        valid, errors, title = yaml_structure_check(content)
        return valid, errors, title, "yaml"
    try:
        valid, errors, title = validator(content)
    except Exception as exc:
        log.warning("sigma validator raised on an LLM-proposed rule: %s", exc)
        return False, [f"validator error: {type(exc).__name__}: {exc}"[:500]], None, "sigma"
    return bool(valid), [str(e) for e in (errors or [])], title, "sigma"


