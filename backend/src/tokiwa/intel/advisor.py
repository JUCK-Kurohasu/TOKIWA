"""LLM vulnerability advisor: "this vulnerability matters to *these* assets, here is what to do".

Priority floor (deterministic, cannot be lowered by the LLM):

- KEV-listed  AND matched to an asset          -> P1 (act now, generated immediately on ``intel.vuln_matched``)
- EPSS >= ``intel.epss_alert_threshold`` AND matched -> P2 (generated immediately)
- other matches                                -> P3 (generated by the periodic ``intel.advise`` job, capped per run)
- no match (manual request only)               -> P4

The final priority is the more urgent of the floor and the LLM's suggestion: a prompt injection hidden in a CVE
description can at worst make an advisory *more* urgent, never suppress it.

LLM output handling (AGENTS.md §2):

- vulnerability text and asset data are wrapped with ``untrusted_block`` (see :mod:`tokiwa.intel.prompts`);
- ``affected_assets`` is filtered to the asset ids we supplied;
- ``references`` are kept only if they come from the vuln record or a trusted domain;
- ``proposed_rules`` are validated with the Sigma validator (``tokiwa.detect.sigma.validate_rule``, falling back to
  a YAML structure check while that module is unavailable) and stored as ``rules(status=proposed, source=llm)``.
  They are never enabled automatically; a human approves them via ``POST /rules/{id}/approve``.

Without an LLM (mock provider, refusal, budget exhausted, invalid output) a rule-based template advisory is stored
instead, so the pipeline never stops. Duplicate generation is avoided: the same vuln + asset set within
:data:`DEDUP_DAYS` days is skipped unless the new priority is more urgent (or ``force=True``).
"""

