async def _matched_assets(vuln_id: str) -> list[AssetContext]:
    async with session_scope() as session:
        rows = (
            await session.execute(
                select(VulnMatchRow, AssetRow)
                .join(AssetRow, AssetRow.id == VulnMatchRow.asset_id)
                .where(VulnMatchRow.vuln_id == vuln_id, VulnMatchRow.status == MatchStatus.OPEN.value)
                .order_by(VulnMatchRow.confidence.desc())
            )
        ).all()
    seen: dict[str, AssetContext] = {}
    for m, a in rows:
        if a.id in seen:
            continue
        seen[a.id] = AssetContext(
            id=a.id,
            name=a.name,
            kind=a.kind,
            criticality=a.criticality,
            software=m.software,
            match_reason=m.reason,
            match_confidence=m.confidence,
        )
    return list(seen.values())


async def _load_vuln(vuln_id: str) -> VulnRecord | None:
    async with session_scope() as session:
        row = await session.get(VulnRow, vuln_id)
        return VulnRecord.model_validate(row) if row is not None else None


async def find_recent_advisory(vuln_id: str, asset_ids: list[str], priority: Priority) -> Advisory | None:
    """An advisory for the same vuln + asset set within DEDUP_DAYS whose priority is at least as urgent."""
    since = utcnow() - timedelta(days=DEDUP_DAYS)
    wanted = sorted(asset_ids)
    async with session_scope() as session:
        rows = (
            await session.execute(
                select(AdvisoryRow)
                .where(
                    AdvisoryRow.created_at >= since,
                    cast(AdvisoryRow.vuln_ids, String).contains(vuln_id, autoescape=True),
                )
                .order_by(AdvisoryRow.created_at.desc())
                .limit(200)
            )
        ).scalars()
        for row in rows:
            if vuln_id not in (row.vuln_ids or []):
                continue
            meta = (row.analysis or {}).get("_meta") or {}
            if meta.get("kind") != "vuln":
                continue
            if sorted(meta.get("input_asset_ids") or []) != wanted:
                continue
            if PRIORITY_RANK.get(Priority(row.priority), 4) <= PRIORITY_RANK[priority]:
                return Advisory.model_validate(row)
    return None


def _vuln_prompt_dict(v: VulnRecord) -> dict[str, Any]:
    return {
        "id": v.id,
        "aliases": v.aliases[:10],
        "title": v.title,
        "description": (v.description or "")[:6000],
        "published": v.published,
        "cvss_score": v.cvss_score,
        "cvss_vector": v.cvss_vector,
        "severity": v.severity,
        "epss": v.epss,
        "epss_percentile": v.epss_percentile,
        "kev": v.kev,
        "kev_date_added": v.kev_date_added,
        "kev_due_date": v.kev_due_date,
        "kev_ransomware": v.kev_ransomware,
        "cwe": v.cwe[:10],
        "affected": [a.model_dump(exclude_none=True) for a in v.affected[:20]],
        "references": v.references[:20],
    }


