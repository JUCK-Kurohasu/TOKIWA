def rule_priority(vuln: VulnRecord, matched: bool, epss_threshold: float) -> tuple[Priority, list[str]]:
    epss = vuln.epss or 0.0
    if matched and vuln.kev:
        return Priority.P1, ["listed in CISA KEV (exploited in the wild)", "matches the asset inventory"]
    if matched and epss >= epss_threshold:
        return Priority.P2, [f"EPSS {epss:.3f} >= threshold {epss_threshold}", "matches the asset inventory"]
    if matched:
        return Priority.P3, ["matches the asset inventory"]
    reasons = ["no asset in the inventory matches"]
    if vuln.kev:
        reasons.append("listed in CISA KEV")
    return Priority.P4, reasons


def more_urgent(a: Priority, b: Priority) -> Priority:
    return a if PRIORITY_RANK[a] <= PRIORITY_RANK[b] else b


@dataclass(frozen=True)
class AssetContext:
    id: str
    name: str
    kind: str
    criticality: str
    software: dict[str, Any] | None
    match_reason: str
    match_confidence: float

    def prompt_dict(self) -> dict[str, Any]:
        return {
            "id": self.id,
            "name": self.name,
            "kind": self.kind,
            "criticality": self.criticality,
            "software": self.software,
            "match_reason": self.match_reason,
            "match_confidence": self.match_confidence,
        }


def _fmt_date(dt: Any) -> str | None:
    return dt.date().isoformat() if dt is not None else None


def template_analysis(
    vuln: VulnRecord,
    assets: list[AssetContext],
    priority: Priority,
    reasons: list[str],
    lang: str = "ja",
) -> AdvisoryAnalysis:
    """Rule-based advisory used without an LLM (and as the mock provider's answer)."""
    ja = lang == "ja"
    names = ", ".join(a.name for a in assets[:5]) + (" ..." if len(assets) > 5 else "")
    title_core = vuln.title or vuln.id
    if ja:
        title = f"{vuln.id}: {title_core}" + (f"（影響資産 {len(assets)} 件）" if assets else "")
    else:
        title = f"{vuln.id}: {title_core}" + (f" ({len(assets)} affected asset(s))" if assets else "")
    if vuln.kev:
        exploitation = (
            f"CISA KEV 掲載（実環境で悪用確認、追加日 {_fmt_date(vuln.kev_date_added) or '不明'}）"
            if ja
            else f"Exploited in the wild (CISA KEV, added {_fmt_date(vuln.kev_date_added) or 'unknown'})"
        )
    elif vuln.epss is not None:
        exploitation = (
            f"悪用の既知情報なし。EPSS {vuln.epss:.3f}"
            if ja
            else f"No known exploitation. EPSS {vuln.epss:.3f}"
        )
    else:
        exploitation = "不明" if ja else "unknown"
    cvss = (
        f"CVSS {vuln.cvss_score}" if vuln.cvss_score is not None else ("CVSS 不明" if ja else "CVSS unknown")
    )
    sev = f" / {vuln.severity}" if vuln.severity else ""
    desc = (vuln.description or "").strip()
    if len(desc) > 800:
        desc = desc[:800] + "..."
    if ja:
        summary = f"{desc or '説明なし'}\n判定根拠: {'; '.join(reasons)}。" + (
            f" 対象: {names}" if assets else ""
        )
        impact = f"{cvss}{sev}" + (f"。CWE: {', '.join(vuln.cwe)}" if vuln.cwe else "")
        mitigations = ["ベンダーのアドバイザリに従い、修正済みバージョンへ更新またはパッチを適用する。"]
        if vuln.kev_due_date:
            mitigations.append(f"CISA KEV の対応期限: {_fmt_date(vuln.kev_due_date)}。")
        mitigations += [
            "パッチ適用まではネットワーク到達性の制限・WAF による仮想パッチ・該当機能の無効化で露出を下げる。",
            "影響資産のログを遡り、悪用の痕跡がないか確認する。",
        ]
        detection = [
            "影響資産への攻撃（exploit_attempt 等）は TOKIWA の vuln_exposure アラートとして相関される。"
        ]
        if vuln.cwe:
            detection.append(f"{', '.join(vuln.cwe)} に典型的なリクエストパターンを監視する。")
    else:
        summary = f"{desc or 'No description.'}\nWhy: {'; '.join(reasons)}." + (
            f" Assets: {names}" if assets else ""
        )
        impact = f"{cvss}{sev}" + (f". CWE: {', '.join(vuln.cwe)}" if vuln.cwe else "")
        mitigations = ["Upgrade to a fixed version or apply the vendor patch per the vendor advisory."]
        if vuln.kev_due_date:
            mitigations.append(f"CISA KEV remediation due date: {_fmt_date(vuln.kev_due_date)}.")
        mitigations += [
            "Until patched, reduce exposure: restrict network reachability, WAF virtual patching, disable the feature.",
            "Review logs of the affected assets for signs of exploitation.",
        ]
        detection = ["Attacks against the affected assets are correlated by TOKIWA as vuln_exposure alerts."]
        if vuln.cwe:
            detection.append(f"Watch for request patterns typical of {', '.join(vuln.cwe)}.")
    avg_conf = sum(a.match_confidence for a in assets) / len(assets) if assets else 0.3
    return AdvisoryAnalysis(
        title=title[:500],
        priority=priority,
        summary=summary,
        exploitation_status=exploitation,
        affected_assets=[a.id for a in assets],
        impact=impact,
        mitigations=mitigations,
        detection_opportunities=detection,
        proposed_rules=[],
        references=[u for u in vuln.references if _is_http_url(u)][:10],
        confidence=round(min(0.6, max(0.2, avg_conf * 0.6)), 2),
    )


