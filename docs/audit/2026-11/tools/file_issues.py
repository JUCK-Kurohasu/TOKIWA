#!/usr/bin/env python3
"""File rendered audit issues through the GitHub REST API (gh api) — no LLM involved.
Reconciles with what already exists (by exact title), creates the missing ones, attaches all to epic #16."""
import json, subprocess, sys, time, collections
from pathlib import Path
A = Path(__file__).resolve().parent; I = A / "issues"; REPO = "repos/JUCK-Kurohasu/TOKIWA"; EPIC = 16
DRY = "--dry" in sys.argv
def opt(name):
    return next((x.split("=", 1)[1].split(",") for x in sys.argv if x.startswith(name + "=")), None)
LANES, SYNC = opt("--lanes"), opt("--sync")
def gh(args, inp=None):
    r = subprocess.run(["gh", "api", *args], input=inp, capture_output=True, text=True, timeout=60)
    if r.returncode != 0: raise RuntimeError(f"gh api {' '.join(args[:3])}: {r.stderr.strip()[:300]} {r.stdout[:200]}")
    return json.loads(r.stdout) if r.stdout.strip() else None
def existing():
    out, page = [], 1
    while True:
        chunk = gh([f"{REPO}/issues?state=all&labels=audit-2026-11&per_page=100&page={page}"])
        out += [i for i in chunk if "pull_request" not in i]
        if len(chunk) < 100: return out
        page += 1
index = json.loads((I / "index.json").read_text())
filed = json.loads((I / "filed.json").read_text()) if (I / "filed.json").exists() else {}
ex = existing(); by_title = collections.defaultdict(list)
for i in ex: by_title[i["title"]].append(i)
dups = {t: [i["number"] for i in v] for t, v in by_title.items() if len(v) > 1}
print(f"existing audit issues: {len(ex)}; duplicate titles: {dups or 'none'}")
for e in index:                       # reconcile: created on GitHub but not recorded
    hit = by_title.get(e["title"])
    if hit:
        first = min(hit, key=lambda i: i["number"])
        filed[e["key"]] = {"number": first["number"], "url": first["html_url"], "id": first["id"]}
todo = [e for e in index if e["key"] not in filed]
if LANES: todo = [e for e in todo if e["key"].split("-")[0] in LANES]
if SYNC:
    by_num = {i["number"]: i for i in ex}; norm = lambda t: "\n".join(x.rstrip() for x in (t or "").replace("\r\n", "\n").splitlines() if x.strip())
    for e in index:
        v = filed.get(e["key"]); cur = by_num.get(v["number"]) if v else None
        if not cur or not (SYNC == ["all"] or e["key"] in SYNC): continue
        body = Path(e["body_file"]).read_text(encoding="utf-8")
        if norm(cur["body"]) != norm(body) or cur["title"] != e["title"]:
            print("sync", e["key"], "#%d" % v["number"], "(dry)" if DRY else "")
            if not DRY: gh(["-X", "PATCH", f"{REPO}/issues/{v['number']}", "--input", "-"], json.dumps({"title": e["title"], "body": body})); time.sleep(1)
print(f"index {len(index)}, filed after reconcile {len(filed)}, to create {len(todo)}")
for e in todo:
    payload = {"title": e["title"], "body": Path(e["body_file"]).read_text(encoding="utf-8"), "labels": e["labels"]}
    if DRY: print("would create", e["key"], e["title"][:60]); continue
    for attempt in range(3):
        try:
            r = gh(["-X", "POST", f"{REPO}/issues", "--input", "-"], json.dumps(payload)); break
        except RuntimeError as err:
            print("retry", e["key"], str(err)[:160]); time.sleep(20 * (attempt + 1))
    else:
        print("FAILED", e["key"]); continue
    filed[e["key"]] = {"number": r["number"], "url": r["html_url"], "id": r["id"]}
    (I / "filed.json").write_text(json.dumps(filed, ensure_ascii=False, indent=1))
    print("created", e["key"], "#%d" % r["number"]); time.sleep(2)
(I / "filed.json").write_text(json.dumps(filed, ensure_ascii=False, indent=1))
EPIC2_TITLE = "[audit] 実運用・対 AI 攻撃ツール監査（2026-11）— 2 巡目・追加観点の指摘（#16 の続き）"
EPIC2_BODY = """GitHub のサブ Issue は 1 つの親につき 100 件までのため、監査の 2 巡目と追加観点（誤検知・評価の妥当性・個人データ・運用など）の指摘はこの Issue にぶら下げます。

**全件の一覧・優先度・読み方は親 Issue #16 を参照してください。**

親 Issue: #16

---
_Generated by [Claude Code](https://claude.ai/code)_
"""
def subs_of(n):
    out, page = {}, 1
    while True:
        chunk = gh([f"{REPO}/issues/{n}/sub_issues?per_page=100&page={page}"]); out.update({s["id"]: s["number"] for s in chunk})
        if len(chunk) < 100: return out
        page += 1
def attach(parent, sid, replace=False):
    gh(["-X", "POST", f"{REPO}/issues/{parent}/sub_issues", "--input", "-"], json.dumps({"sub_issue_id": sid, "replace_parent": replace})); time.sleep(0.7)
if not DRY:
    e2 = next((i for i in ex if i["title"] == EPIC2_TITLE), None)
    if not e2:
        e2 = gh(["-X", "POST", f"{REPO}/issues", "--input", "-"], json.dumps({"title": EPIC2_TITLE, "body": EPIC2_BODY, "labels": ["audit-2026-11"]}))
        print("created second parent #%d" % e2["number"])
    (I / "parents.json").write_text(json.dumps({"epic": EPIC, "epic2": e2["number"]}))
    s1, s2 = subs_of(EPIC), subs_of(e2["number"])
    if e2["id"] not in s1:
        if len(s1) >= 100:                     # free slots: move the pass-2 issues that already sit under the first parent
            for sid, num in sorted(s1.items(), key=lambda kv: -kv[1])[:5]:
                attach(e2["number"], sid, replace=True); s2[sid] = num; del s1[sid]; print("moved #%d under #%d" % (num, e2["number"]))
        attach(EPIC, e2["id"]); print("attached second parent to #%d" % EPIC)
    n = 0
    for k, v in filed.items():
        if v.get("id") and v["id"] not in s1 and v["id"] not in s2:
            try: attach(e2["number"], v["id"]); n += 1
            except RuntimeError as err: print("attach failed", k, str(err)[:200])
    print(f"attached {n}; #{EPIC} has {len(s1) + 1} sub-issues, #{e2['number']} has {len(s2) + n}")
print("filed total:", len(filed))
