#!/usr/bin/env python3
"""Merge audit findings (findings/*.jsonl), validate them and print a triage table.

    python3 consolidate.py summary            # table of all findings
    python3 consolidate.py show <id> [...]    # full records
    python3 consolidate.py render <plan.json> # issue bodies for the filing plan -> issues/<key>.md + issues/index.json
"""

from __future__ import annotations

import json
import sys
from pathlib import Path

AUDIT = Path(__file__).resolve().parent
FINDINGS = AUDIT / "findings"
SEV_ORDER = {"critical": 0, "high": 1, "medium": 2, "low": 3, "info": 4}
CONF_JA = {"confirmed": "再現済み", "likely": "コード上で確認（未実行）", "hypothesis": "推測（要検証）"}
REQUIRED = ["id", "title", "area", "category", "severity", "confidence", "summary", "evidence", "recommendation"]


def load() -> list[dict]:
    out: list[dict] = []
    for f in sorted(FINDINGS.glob("*.jsonl")):
        for n, line in enumerate(f.read_text(encoding="utf-8").splitlines(), 1):
            line = line.strip()
            if not line:
                continue
            try:
                d = json.loads(line)
            except json.JSONDecodeError as e:
                print(f"!! {f.name}:{n} bad JSON: {e}", file=sys.stderr)
                continue
            missing = [k for k in REQUIRED if not d.get(k)]
            if missing:
                print(f"!! {f.name}:{n} {d.get('id')} missing {missing}", file=sys.stderr)
            d["_file"] = f.name
            out.append(d)
    return out


def summary(items: list[dict]) -> None:
    items = sorted(items, key=lambda d: (SEV_ORDER.get(d.get("severity", "info"), 9), d.get("area", ""), d["id"]))
    counts: dict[str, int] = {}
    for d in items:
        counts[d.get("severity", "?")] = counts.get(d.get("severity", "?"), 0) + 1
        print(
            f"{d['id']:<16} {d.get('severity', '?'):<8} {d.get('confidence', '?'):<10} "
            f"{d.get('area', '?'):<11} {d.get('known', 'none')[:14]:<14} {d.get('title', '')[:90]}"
        )
    print("\nTOTAL", len(items), counts)


def render(plan_path: Path) -> None:
    """plan.json: [{"key","title","severity","confidence","area","category","effort","ids":[...],
    "summary","evidence","attack_scenario","recommendation","known","references","related","labels_extra":[...]}]"""
    plan = json.loads(plan_path.read_text(encoding="utf-8"))
    outdir = AUDIT / "issues"
    outdir.mkdir(exist_ok=True)
    index = []
    for it in plan:
        refs = "\n".join(f"- {u}" for u in it.get("references", [])) or "- なし"
        related = "、".join(it.get("related", [])) or "なし"
        body = f"""## 概要
{it["summary"]}

## 根拠
{it["evidence"]}

## 攻撃シナリオ / 運用で起きること
{it.get("attack_scenario") or "—"}

## 推奨対応
{it["recommendation"]}

## メタ情報
- 重大度: **{it["severity"]}** / 確度: **{it["confidence"]}**（{CONF_JA.get(it["confidence"], "")}）/ 工数目安: {it.get("effort", "?")}
- 領域: `{it["area"]}` / 区分: `{it["category"]}`
- 既知の計画との関係: {it.get("known") or "なし"}
- 関連: {related}
- 監査の元データ: {", ".join(it["ids"])}

### 参考
{refs}

親 Issue: #16

---
_Generated by [Claude Code](https://claude.ai/code)_
"""
        labels = [
            "audit-2026-11",
            f"severity:{it['severity']}",
            f"confidence:{it['confidence']}",
            f"area:{it['area']}",
            f"type:{it['category']}",
            *it.get("labels_extra", []),
        ]
        (outdir / f"{it['key']}.md").write_text(body, encoding="utf-8")
        index.append({"key": it["key"], "title": it["title"], "labels": labels, "body_file": f"{it['key']}.md"})
    (outdir / "index.json").write_text(json.dumps(index, ensure_ascii=False, indent=1), encoding="utf-8")
    print(f"rendered {len(index)} issues -> {outdir}")


if __name__ == "__main__":
    cmd = sys.argv[1] if len(sys.argv) > 1 else "summary"
    if cmd == "summary":
        summary(load())
    elif cmd == "show":
        want = set(sys.argv[2:])
        for d in load():
            if d["id"] in want:
                print(json.dumps(d, ensure_ascii=False, indent=1))
    elif cmd == "render":
        render(Path(sys.argv[2]))
