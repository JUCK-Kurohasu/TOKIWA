#!/usr/bin/env python3
"""Render issue bodies straight from findings JSONL.  python3 render2.py [--only-new]
Merges: MERGE maps primary id -> secondary ids (same root cause reported by another lane).
Keeps issues/index.json (all rendered) ; issues/filed.json (key -> issue number) is written by the filer."""
import json, re, sys
from pathlib import Path
A = Path(__file__).resolve().parent
OUT = A / "issues"; OUT.mkdir(exist_ok=True)
MERGE = json.loads((A / "merge.json").read_text()) if (A / "merge.json").exists() else {}
SKIP = set(json.loads((A / "skip.json").read_text())) if (A / "skip.json").exists() else set()
CONF = {"confirmed": "再現済み", "likely": "コード上で確認（未実行）", "hypothesis": "推測（要検証）"}
ABS = str(A)
def fix(text, lane):
    t = text or ""
    t = t.replace(ABS + "/agents/", "docs/audit/2026-11/repro/").replace("$AUDIT_DIR/agents/", "docs/audit/2026-11/repro/")
    t = t.replace("AUDIT_DIR/agents/", "docs/audit/2026-11/repro/")
    t = re.sub(r"\$?\{?MYDIR\}?/", f"docs/audit/2026-11/repro/{lane}/", t)
    t = re.sub(r"(?<![\w/])agents/(L\d\d)/", r"docs/audit/2026-11/repro/\1/", t)
    return t
items = {}
for f in sorted((A / "findings").glob("*.jsonl")):
    for line in f.read_text(encoding="utf-8").splitlines():
        if line.strip():
            d = json.loads(line); items[d["id"]] = d
secondary = {s for v in MERGE.values() for s in v}
index = []
for fid, d in sorted(items.items()):
    if fid in secondary or fid in SKIP: continue
    lane = fid.split("-")[0]
    extra = ""
    for sid in MERGE.get(fid, []):
        s = items[sid]
        extra += f"\n### 同じ原因の別レーンの報告（{sid}）\n**{s['title']}**\n\n{fix(s.get('evidence'), sid.split('-')[0])}\n"
    refs = "\n".join(f"- {u}" for u in d.get("references") or []) or "- なし"
    rel = d.get("related") or []
    related = "、".join(map(str, rel)) if isinstance(rel, list) else str(rel)
    body = f"""## 概要
{fix(d['summary'], lane)}

## 根拠
{fix(d['evidence'], lane)}
{extra}
## 攻撃シナリオ / 運用で起きること
{fix(d.get('attack_scenario'), lane) or '—'}

## 推奨対応
{fix(d['recommendation'], lane)}

## メタ情報
- 重大度: **{d['severity']}** / 確度: **{d['confidence']}**（{CONF.get(d['confidence'], '')}）/ 工数目安: {d.get('effort', '?')}
- 領域: `{d['area']}` / 区分: `{d['category']}`
- 既知の計画との関係: {d.get('known') or 'なし'}
- 関連: {related or 'なし'}
- 監査の元データ ID: {', '.join([fid, *MERGE.get(fid, [])])}
- 再現スクリプトの置き場所（本文中のパス）: `docs/audit/2026-11/repro/{lane}/`（監査時の作業ファイル。リポジトリへの収録は別 PR で行う）

### 参考
{refs}

親 Issue: #16

---
_Generated by [Claude Code](https://claude.ai/code)_
"""
    labels = ["audit-2026-11", f"severity:{d['severity']}", f"confidence:{d['confidence']}", f"area:{d['area']}", f"type:{d['category']}"]
    if "needs-live-llm" in json.dumps(rel, ensure_ascii=False): labels.append("needs-live-llm")
    (OUT / f"{fid}.md").write_text(body, encoding="utf-8")
    index.append({"key": fid, "title": f"[{d['area']}] {d['title']}"[:240], "labels": labels, "body_file": str(OUT / f"{fid}.md"), "severity": d["severity"]})
order = {"critical": 0, "high": 1, "medium": 2, "low": 3, "info": 4}
index.sort(key=lambda x: (order.get(x["severity"], 9), x["key"]))
(OUT / "index.json").write_text(json.dumps(index, ensure_ascii=False, indent=1), encoding="utf-8")
filed = json.loads((OUT / "filed.json").read_text()) if (OUT / "filed.json").exists() else {}
print(f"rendered {len(index)} issues; already filed {len(filed)}; pending {len([i for i in index if i['key'] not in filed])}")
